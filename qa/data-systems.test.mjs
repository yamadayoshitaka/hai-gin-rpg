import assert from 'node:assert/strict';
import {WorldCompositionSystem,ActorStateSystem,BuildingCapabilitySystem,StairGeometrySystem} from '../src/data-systems.js';
import {createAreaBlueprint} from '../src/world-blueprints.js';
import {createActorDefinition} from '../src/actor-definitions.js';
const area=createAreaBlueprint({id:'town',buildings:[{id:2,kind:'weapons'}],actors:[{id:'keeper',buildingId:2}],objects:[{id:'shelf',buildingId:2}]});
const output=new WorldCompositionSystem().execute({area});
assert.ok(output.nodes.some(x=>x.id==='building:2'));
assert.ok(output.nodes.some(x=>x.type==='actor'&&x.parentId==='floor:2:1'));
assert.ok(output.nodes.some(x=>x.type==='object'&&x.parentId==='floor:2:1'));
const building=area.buildings[0];
assert.equal(new BuildingCapabilitySystem().execute({building,action:'shop'}).permitted,true);
assert.equal(new BuildingCapabilitySystem().execute({building,action:'inn'}).permitted,false);
const actor=new ActorStateSystem().execute({definition:createActorDefinition({id:'hero',template:'hero'}),state:{hp:75},equipment:{weapon:'iron'}});
assert.equal(actor.stats.hp,75);
assert.equal(actor.equipment.weapon,'iron');
const stairs=new StairGeometrySystem().execute({stair:building.stair,floorY:.1});
assert.equal(stairs.steps.length,11);
assert.ok(stairs.steps.every((x,i)=>i===0||x.top>stairs.steps[i-1].top));
assert.ok(stairs.opening.width>building.stair.width);
console.log('Stateless data systems passed');