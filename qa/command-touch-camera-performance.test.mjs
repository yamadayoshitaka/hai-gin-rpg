import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {SourceTextModule} from 'node:vm';
import {AdaptiveBattleResolution} from '../src/adaptive-battle-resolution.js';
const quality=new AdaptiveBattleResolution({maxRatio:1.2,minRatio:.75,targetFps:45,intervalMs:1000});
assert.equal(quality.sample({fps:30,p95Ms:40,nowMs:1000}),null);
assert.equal(quality.sample({fps:30,p95Ms:40,nowMs:2000}),1.125);
assert.equal(quality.sample({fps:44,p95Ms:24,nowMs:3000}),null);
let out=null;
for(const t of [4000,5000,6000,7000])out=quality.sample({fps:60,p95Ms:17,nowMs:t});
assert.equal(out,1.165);
assert.equal(quality.sample({fps:10,p95Ms:80,nowMs:8000,paused:true}),null);
assert.equal(quality.getStats().ratio,1.165);
for(let t=9000;t<30000;t+=1000)quality.sample({fps:12,p95Ms:65,nowMs:t});
assert.ok(quality.ratio>=.75&&quality.ratio<1,'reduces GPU fill-rate within safe bounds');
const low=quality.ratio;
for(let t=31000;t<90000;t+=1000)quality.sample({fps:60,p95Ms:17,nowMs:t});
assert.equal(quality.ratio,1.2,'recovers original quality without overshoot');
assert.throws(()=>new AdaptiveBattleResolution({maxRatio:.5,minRatio:1}),/bounds/);
