import assert from 'node:assert/strict';
import {situationLevel,createBattleSituationMonitor} from '../src/battle-situation-monitor.js';
const sum=(n,total,hp=100,maxHp=100)=>({n,total,hp,maxHp});
assert.equal(situationLevel(sum(100,100)),0);
assert.equal(situationLevel(sum(80,100,60,100)),1,'HP can warn without deaths');
assert.equal(situationLevel(sum(90,100,40,100)),2,'HP loss triggers group reconsideration');
assert.equal(situationLevel(sum(80,100,20,100)),3,'low HP is critical');
assert.equal(situationLevel(sum(0,100,0,100)),0,'dead squads use result cutin');
const monitor=createBattleSituationMonitor();
monitor.observe([{id:'group1',row:sum(100,100)}]);
monitor.observe([{id:'group1',row:sum(80,100,40,100)},{id:'group2',row:sum(25,100,100,100)}]);
assert.equal(monitor.peek().id,'group2','critical takes priority over earlier moderate');
assert.equal(monitor.snapshot().pending.length,2,'simultaneous events must not be dropped');
assert.equal(monitor.peek().id,'group2','paused UI must preserve the event until acknowledged');
monitor.acknowledge('group2');
assert.equal(monitor.peek().id,'group1');
monitor.acknowledge('group1');
assert.equal(monitor.peek(),null);
monitor.observe([{id:'group1',row:sum(80,100,20,100)}]);
assert.equal(monitor.peek().level,3,'escalating HP triggers new event');
monitor.observe([{id:'group1',row:sum(80,100,100,100)}]);
assert.equal(monitor.peek(),null,'recovered pending alert must not interrupt');
monitor.enqueue('group1',{title:'防衛目標失敗',severity:'critical'});
monitor.observe([{id:'group1',row:sum(100,100,100,100)}]);
assert.equal(monitor.peek()?.kind,'objective','objective failures do not disappear when soldiers are healthy');
assert.equal(monitor.peek()?.title,'防衛目標失敗');
monitor.acknowledge('group1');
console.log('battle situation warning inbox: OK');
