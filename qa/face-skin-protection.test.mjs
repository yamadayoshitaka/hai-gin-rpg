import assert from 'node:assert/strict';
import * as THREE from 'three';
import {protectFaceSkin} from '../src/character-system/skin-face-protection.js';
const root=new THREE.Group();
const skinMap=new THREE.Texture();
const sourceSkin=new THREE.MeshStandardMaterial({name:'MI_Superhero_Male',map:skinMap,color:0xe6b18b});
const skinMesh=new THREE.SkinnedMesh(new THREE.BoxGeometry(),sourceSkin);
skinMesh.name='SuperHero_Male';skinMesh.receiveShadow=true;
const costume=new THREE.SkinnedMesh(new THREE.BoxGeometry(),new THREE.MeshStandardMaterial({name:'MI_Ranger',color:0x1a1a1a}));
costume.receiveShadow=true;
root.add(skinMesh,costume);
const beforeColor=skinMesh.material.color.getHex(),beforeMap=skinMesh.material.map;
const result=protectFaceSkin(root);
assert.equal(result.protectedMeshes,1);
assert.equal(result.protectedMaterials,1);
assert.equal(skinMesh.receiveShadow,false,'Face should not go black under oversized UR collar');
assert.equal(costume.receiveShadow,true,'Keep shadows on armor and fabric');
assert.equal(skinMesh.material.map,beforeMap,'Never discard the original skin photo texture');
assert.equal(skinMesh.material.color.getHex(),beforeColor,'Never tint skin with job or rarity colors');
console.log('PASS face skin PBR material and shadow guard');
