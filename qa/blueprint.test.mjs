import assert from 'node:assert/strict';
import {createBuildingBlueprint,createAreaBlueprint,validateBlueprint} from '../src/world-blueprints.js';
const home=createBuildingBlueprint({id:'a',kind:'home'});
const manor=createBuildingBlueprint({id:'b',kind:'manor'});
assert.deepEqual(home.size,[42,39]);
const weaponShop=createBuildingBlueprint({id:'shop',kind:'weapons'});
assert.equal(weaponShop.attributes.usage,'retail');
assert.equal(weaponShop.attributes.shopCategory,'weapons');
assert.ok(weaponShop.attributes.capabilities.includes('shop'));
const customInn=createBuildingBlueprint({id:'inn-store',kind:'inn',attributes:{capabilities:['inn','shop'],shopCategory:'items'}});
assert.deepEqual(customInn.attributes.capabilities,['inn','shop']);
assert.deepEqual(manor.size,[54,48]);
assert.equal(home.stair.steps,11);
assert.equal(home.stair.z,-39*.25);
assert.equal(home.stair.bottomZ-home.stair.z,home.stair.run/2+1.4);
const custom=createBuildingBlueprint({id:'c',kind:'weapons',width:30,depth:26,actors:[{floor:2,id:'keeper'}],objects:[{floor:1,id:'shelf'}]});
assert.deepEqual(custom.size,[30,26]);
const placed=createAreaBlueprint({id:'nested',buildings:[{id:42,kind:'weapons'}],actors:[{id:'keeper',buildingId:42}],objects:[{id:'rack',buildingId:42}],});
assert.equal(placed.actors.length,0);
assert.equal(placed.objects.length,0);
assert.equal(placed.buildings[0].floors[0].actors[0].id,'keeper');
assert.equal(placed.buildings[0].floors[0].objects[0].id,'rack');
const customStair=createBuildingBlueprint({kind:'home',stair:{steps:15,run:7,rise:3.1}});
assert.equal(customStair.stair.steps,15);
assert.equal(custom.floors[1].actors[0].id,'keeper');
assert.equal(custom.floors[0].objects[0].id,'shelf');
const area=createAreaBlueprint({id:'town',buildings:[{id:'one',kind:'home'},{id:'two',kind:'manor'}],actors:[{id:'walker'}],objects:[{id:'bench'}]});
assert.equal(area.buildings.length,2);
assert.equal(area.actors[0].id,'walker');
assert.deepEqual(validateBlueprint(area),[]);
const bad=createAreaBlueprint({id:'bad',buildings:[{id:'broken',width:-1}]});
assert.ok(validateBlueprint(bad).length>0);
console.log('Blueprint parameterization tests passed');
