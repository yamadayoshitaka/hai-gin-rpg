export function storyProgress(state){
 if(!state)return 0;
 if(state.gameOver&&/天下統一|制圧/.test(state.gameOver))return 999;
 const owners=state.owners||{},player=Object.values(owners).filter(x=>x==='player').length;
 const fallenBases=['flame-fort','green-capital'].filter(id=>owners[id]==='player').length;
 return Math.max(0,(Math.max(1,Number(state.month)||1)-1)*2+Math.max(0,player-3)*2+fallenBases*4);
}
export function unlockedStoryChapters(state){
 if(!state)return 1;
 let count=1;
 for(const chapter of STORY_CHAPTERS){
  if(chapter.id===20&&!state.completedStages?.includes('c19-s10')&&!['flame-fort','green-capital'].every(id=>state.owners?.[id]==='player'))break;
  if(chapter.score>storyProgress(state))break;
  count=chapter.id;
 }
 return count;
}
