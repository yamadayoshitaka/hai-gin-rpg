import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {chapterOneReviewPages} from '../src/story-chapter1-review-core.js';
import {CHAPTER1_PROVISIONAL_LIVE as live} from '../src/story-chapter1-provisional-live.js';
import {registeredStoryPanelAsset} from '../src/story-panel-registered-art.js';
const key='c01-s04|pre|female|c01-s04-m5';
const shot=chapterOneReviewPages().flatMap(p=>p.shots).find(s=>s.key===key);
const record=live[key], proof=JSON.parse(fs.readFileSync(record.provenance));
const hash=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
assert.deepEqual([shot.characterId,shot.secondaryId],['lucia','vess']);
assert.equal(proof.scriptText,shot.scriptText);
assert.equal(proof.imageSha256,hash(record.asset));
assert.equal(proof.imageSha256,hash(record.sourceDraft));
assert.deepEqual(proof.nativePixels,[1664,936]);
assert.equal(proof.nativePixels[0]*9,proof.nativePixels[1]*16);
assert.equal(proof.generationReferencesAttached,true);
for(const ref of proof.referenceImagesAttached)assert.equal(hash(ref.path),ref.sha256);
assert.equal(proof.humanVisualQAConfirmed,false);
assert.equal(proof.finalP0Approved,false);
assert.equal(record.originalLivePath,null);
assert.equal(record.status,'PROVISIONAL_OWNER_AUTHORIZED_PENDING_P0');
const resolved=registeredStoryPanelAsset({stageId:shot.stageId,comicEdition:shot.edition,protagonistGender:shot.gender,id:shot.shotId});
assert.equal(typeof resolved==='string'?resolved:resolved?.asset,record.asset);
const rerun=spawnSync(process.execPath,['scripts/import-story-chapter1-chatgpt-staging.mjs','--plan',key],{encoding:'utf8'});
assert.equal(rerun.status,0,rerun.stderr);
assert.equal(JSON.parse(rerun.stdout).eligible,0,'Duplicate import must be a no-op');
const invalid=spawnSync(process.execPath,['scripts/import-story-chapter1-chatgpt-staging.mjs','--plan',key+'-invalid'],{encoding:'utf8'});
assert.notEqual(invalid.status,0,'Unknown canonical key must be rejected');
console.log('PASS: pilot exact cast, canonical script, reference hashes, branch resolver, reversible provisional provenance, duplicate no-op, unknown-key rejection');
